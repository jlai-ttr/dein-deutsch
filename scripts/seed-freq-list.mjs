const TARGET = 'app/woerter/page.tsx';
const OUT_JSON = '.tmp-freq.json';

function fetch(url) {
  return new Promise((res, rej) => {
    https.get(url, r => {
      if (r.statusCode !== 200) return rej(new Error('HTTP ' + r.statusCode));
      let d = '';
      r.on('data', c => d += c);
      r.on('end', () => res(d));
      r.on('error', rej);
    }).on('error', rej);
  });
}

