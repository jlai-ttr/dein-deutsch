// Strategy:
// 1. Pull top-1000 frequency list from hermitdave/FrequencyWords (OpenSubtitles 2018)
// 2. Map rank to CEFR (A1: 1-100, A2: 101-300, B1: 301-600, B2: 601-850, C1: 851-1000)
// 3. Use built-in KNOWN_EN dictionary for ~700 words
// 4. For unrecognized words, leave translation field blank (will show "learn new word" prompt)
// 5. Skip words already in seed

import https from 'node:https';
import fs from 'node:fs';

